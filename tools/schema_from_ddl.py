"""Build boolean_columns.txt (A024) and column_types.txt (A054) from PostgreSQL DDL.

Usage:
    python -m tools.schema_from_ddl <schema.sql> [<more.sql> ...] [--out DIR]

<schema.sql> is any PostgreSQL DDL that holds CREATE TABLE statements:
    * `pg_dump --schema-only` of the target database (best: the real schema), or
    * the EF Core create script (`context.Database.GenerateCreateScript()` with the
      Npgsql provider) when no database is reachable.

Writes into DIR (default: the folder of this checkout):
    boolean_columns.txt  -- names that are BOOLEAN in every table declaring them
    column_types.txt     -- `table.column<TAB>type`, one line per column

With a live database you can export the same two files with
boolean_columns_query.sql and column_types_query.sql instead.
"""
from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

_CREATE = re.compile(
    r'CREATE\s+(?:UNLOGGED\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?((?:"?[\w$]+"?\.)?"?[\w$]+"?)\s*\((.*?)\)\s*(?:INHERITS|PARTITION|WITH|TABLESPACE|;)',
    re.IGNORECASE | re.DOTALL)
_SKIP_LINE = re.compile(r'^\s*(CONSTRAINT|PRIMARY\s+KEY|FOREIGN\s+KEY|UNIQUE|CHECK|EXCLUDE|LIKE)\b', re.IGNORECASE)
_COLUMN = re.compile(r'^\s*"?([\w$]+)"?\s+(.+?)\s*$', re.DOTALL)
_TYPE_END = re.compile(r'\s+(NOT\s+NULL|NULL|DEFAULT|GENERATED|CONSTRAINT|PRIMARY|REFERENCES|COLLATE|CHECK|UNIQUE)\b', re.IGNORECASE)


def _split_columns(body: str) -> list[str]:
    parts, depth, start = [], 0, 0
    for i, ch in enumerate(body):
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        elif ch == ',' and depth == 0:
            parts.append(body[start:i])
            start = i + 1
    parts.append(body[start:])
    return [p.strip() for p in parts if p.strip()]


def parse_ddl(text: str) -> dict[str, dict[str, str]]:
    """{table: {column: declared type}}, names lower-cased, schema prefix dropped."""
    text = re.sub(r'--[^\n]*', '', text)
    tables: dict[str, dict[str, str]] = {}
    for m in _CREATE.finditer(text):
        table = m.group(1).replace('"', '').split('.')[-1].lower()
        cols = tables.setdefault(table, {})
        for item in _split_columns(m.group(2)):
            if _SKIP_LINE.match(item):
                continue
            cm = _COLUMN.match(item)
            if not cm:
                continue
            col_type = _TYPE_END.split(cm.group(2), maxsplit=1)[0].strip()
            cols.setdefault(cm.group(1).lower(), col_type.lower())
    return tables


def boolean_names(tables: dict[str, dict[str, str]]) -> list[str]:
    seen: dict[str, set[bool]] = defaultdict(set)
    for cols in tables.values():
        for col, typ in cols.items():
            seen[col].add(typ.split('(')[0].strip() in ('boolean', 'bool'))
    return sorted(c for c, kinds in seen.items() if kinds == {True})


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('ddl', nargs='+', help='DDL file(s): pg_dump --schema-only or an EF create script')
    ap.add_argument('--out', default=str(Path(__file__).resolve().parent.parent), help='output folder')
    ap.add_argument('--merge-boolean', metavar='FILE',
                    help='also keep the names of an existing boolean_columns.txt (hand-confirmed flags) '
                         'unless the DDL declares them non-boolean')
    args = ap.parse_args(argv)

    tables: dict[str, dict[str, str]] = {}
    for path in args.ddl:
        for table, cols in parse_ddl(Path(path).read_text(encoding='utf-8-sig', errors='replace')).items():
            merged = tables.setdefault(table, {})
            for col, typ in cols.items():
                merged.setdefault(col, typ)
    if not tables:
        print('No CREATE TABLE statements found.')
        return 1

    out = Path(args.out)
    names = boolean_names(tables)
    if args.merge_boolean:
        from core.schema_hints import parse
        declared = {c: typ for cols in tables.values() for c, typ in cols.items()}
        extra = [n for n in parse(Path(args.merge_boolean).read_text(encoding='utf-8-sig'))
                 if n not in names and declared.get(n, 'boolean').split('(')[0].strip() in ('boolean', 'bool')]
        names = sorted(set(names) | set(extra))
    header = f'# Generated by tools/schema_from_ddl.py from {", ".join(Path(p).name for p in args.ddl)}\n'
    (out / 'boolean_columns.txt').write_text(
        header + '# Column names that are BOOLEAN in every table declaring them (rule A024).\n'
        + '\n'.join(names) + '\n', encoding='utf-8')
    lines = [f'{t}.{c}\t{typ}' for t in sorted(tables) for c, typ in sorted(tables[t].items())]
    (out / 'column_types.txt').write_text(
        header + '# table.column<TAB>type for every column (rule A054).\n' + '\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(tables)} tables, {len(lines)} columns, {len(names)} boolean column names -> {out}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
